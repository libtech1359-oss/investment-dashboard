'use strict';
require('dotenv').config();

const { saveDraft } = require('./lib/noteDraft');

const title = '毎日の値動きに疲れたので、「月に一度だけ資産と向き合う」投資管理シートを作りました。';

const body = `投資を始めると、毎日証券口座を開いてしまう。

今日は上がった。
今日は下がった。

気になって、何度もアプリを開いてしまう。

でも、長期投資って本来そういうものじゃないと思うんです。

---

私は積立投資を続けています。

大切なのは、

**「毎日相場を見ること」ではなく、長く続けること。**

だから、自分のために投資管理シートを作りました。

そして、せっかくなら同じような人にも使ってもらえたらと思い、配布することにしました。

---

## コンセプトはシンプル

**月に一度だけ資産を確認する。**

証券口座を開いて、現在評価額を入力するだけ。

あとは自動で集計されます。

毎日の値動きを追う必要はありません。

---

## Lite版（無料）

こんな方におすすめです。

- 積立NISAを始めたばかり
- シンプルに資産管理したい
- スプレッドシートが苦手
- まず無料で試したい

**できること**

✅ 購入履歴管理
✅ 保有資産一覧
✅ 月別購入額集計
✅ 総資産・損益確認

黄色いセルだけ入力すれば使える設計です。

---

## Pro版（100円）

Lite版をベースに、さらに「続けたくなる」工夫を追加しました。

**Pro限定機能**

📊 資産配分円グラフ
🤖 AI Capitalからのメッセージ
📈 積立進捗バー
📊 投資割合・現金割合表示
🌱 モチベーションメッセージ
📅 月1回の資産チェック通知

数式セルは保護されているため、初心者でも安心して利用できます。

---

## Lite版とPro版の違い

| 機能 | Lite | Pro |
|---|:---:|:---:|
| 購入履歴管理 | ✅ | ✅ |
| 損益計算 | ✅ | ✅ |
| Dashboard | ✅ | ✅ |
| 円グラフ | － | ✅ |
| AIメッセージ | － | ✅ |
| 積立進捗 | － | ✅ |
| 資産チェック通知 | ✅ | ✅ |
| 数式保護 | ✅ | ✅ |

※入力データはそのままPro版へ引き継げます。

---

## AI Capitalらしいシートを目指しました。

このシートは、

**「利益を増やす魔法のツール」ではありません。**

資産管理を習慣にするためのツールです。

毎月一度だけ、自分の資産と向き合う。

その積み重ねが、長期投資では一番大切だと思っています。

---

## 配布について

🆓 **Lite版：無料**
💎 **Pro版：100円**

「まずは無料で試してみたい」という方はLite版からどうぞ。

気に入っていただけたら、Pro版でさらに快適に資産管理を続けてもらえたら嬉しいです。

---

このシートも、AI社員たちが市場を分析している「AI Capital」プロジェクトから生まれました。

これからも、投資を少し楽しく、少し続けやすくするツールを作っていきます。`;

(async () => {
  console.log('[portfolio-sheet] note下書き保存を開始します');
  console.log('[portfolio-sheet] タイトル:', title);

  const result = await saveDraft({
    title,
    body,
    thumbPath:        null,
    historyChartPath: null,
    chartPath:        null,
  });

  console.log('\n=== 完了 ===');
  console.log('note URL:', result?.noteUrl || '（未取得）');
  process.exit(0);
})().catch(err => {
  console.error('[portfolio-sheet] エラー:', err.message);
  process.exit(1);
});
