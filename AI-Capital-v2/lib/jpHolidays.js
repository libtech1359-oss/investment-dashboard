'use strict';

/**
 * 日本の国民の祝日（固定リスト方式）
 * 出典: 国立天文台暦計算室 令和8年(2026)暦要項
 *   https://eco.mtk.nao.ac.jp/koyomi/yoko/2026/rekiyou261.html （2026-08-11 確認）
 * 振替休日・国民の休日を含む。
 *
 * 春分の日・秋分の日は国立天文台が前年2月に官報で確定するため、
 * 年をまたぐ前に翌年分をこのリストへ追記すること。
 */
const HOLIDAYS = new Set([
  // 2026年（令和8年）
  '2026-01-01', // 元日
  '2026-01-12', // 成人の日
  '2026-02-11', // 建国記念の日
  '2026-02-23', // 天皇誕生日
  '2026-03-20', // 春分の日
  '2026-04-29', // 昭和の日
  '2026-05-03', // 憲法記念日
  '2026-05-04', // みどりの日
  '2026-05-05', // こどもの日
  '2026-05-06', // 振替休日
  '2026-07-20', // 海の日
  '2026-08-11', // 山の日
  '2026-09-21', // 敬老の日
  '2026-09-22', // 国民の休日
  '2026-09-23', // 秋分の日
  '2026-10-12', // スポーツの日
  '2026-11-03', // 文化の日
  '2026-11-23', // 勤労感謝の日
]);

/** @param {string} dateStr YYYY-MM-DD (JST) */
function isJpHoliday(dateStr) {
  return HOLIDAYS.has(dateStr);
}

module.exports = { isJpHoliday };
